"""Start/stop a local PowerContext 1.4.1 Server (SQLite storage, no model required)."""

from __future__ import annotations

import os
import shutil
import signal
import socket
import subprocess
import sys
import time
from pathlib import Path

import httpx

from sdd_context.config import Settings


class ServerError(RuntimeError):
    pass


def env_file(settings: Settings) -> Path:
    return settings.pc_home / "server.env"


def pid_file(settings: Settings) -> Path:
    return settings.pc_home / "server.pid"


def log_file(settings: Settings) -> Path:
    return settings.pc_home / "server.log"


def write_env(settings: Settings) -> Path:
    settings.pc_home.mkdir(parents=True, exist_ok=True)
    path = env_file(settings)
    path.write_text(
        "\n".join(
            [
                "# Generated by `sdd init`; PowerContext Server for the SDD context module.",
                f"POWERCONTEXT_HOME={settings.pc_home / 'home'}",
                f"POWERCONTEXT_SERVER_HTTP_HOST={settings.pc_host}",
                f"POWERCONTEXT_SERVER_HTTP_PORT={settings.pc_port}",
                "POWERCONTEXT_SERVER_DATABASE_KIND=sqlite",
                f"POWERCONTEXT_SERVER_DATABASE_URL=sqlite+aiosqlite:///{settings.pc_home / 'powercontext.db'}",
                "POWERCONTEXT_SERVER_ACCESS_MODE=disabled",
                "POWERCONTEXT_SERVER_DASHBOARD_ENABLED=true",
                "",
            ]
        ),
        encoding="utf-8",
    )
    path.chmod(0o600)
    return path


def _executable() -> str:
    candidate = Path(sys.executable).parent / "powercontext"
    if candidate.exists():
        return str(candidate)
    found = shutil.which("powercontext")
    if not found:
        raise ServerError("找不到 powercontext 可执行文件；请先运行 scripts/install.sh")
    return found


def is_live(settings: Settings) -> bool:
    try:
        response = httpx.get(f"{settings.pc_url}/health/live", timeout=2.0)
    except httpx.HTTPError:
        return False
    return response.status_code == 200


def _port_open(settings: Settings) -> bool:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.settimeout(0.5)
        return sock.connect_ex((settings.pc_host, settings.pc_port)) == 0


def read_pid(settings: Settings) -> int | None:
    try:
        return int(pid_file(settings).read_text().strip())
    except (FileNotFoundError, ValueError):
        return None


def _alive(pid: int) -> bool:
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True
    return True


def status(settings: Settings) -> dict[str, object]:
    pid = read_pid(settings)
    return {
        "url": settings.pc_url,
        "pid": pid if pid and _alive(pid) else None,
        "live": is_live(settings),
        "env_file": str(env_file(settings)),
        "log_file": str(log_file(settings)),
        "database": str(settings.pc_home / "powercontext.db"),
    }


def start(settings: Settings, timeout: float = 90.0) -> dict[str, object]:
    if is_live(settings):
        return dict(status(settings), started=False)
    if _port_open(settings):
        raise ServerError(f"端口 {settings.pc_port} 已被其他进程占用；请设置 SDD_PC_PORT 换一个端口")
    path = env_file(settings) if env_file(settings).exists() else write_env(settings)
    log = log_file(settings).open("ab")
    env = {key: value for key, value in os.environ.items() if not key.startswith("POWERCONTEXT_")}
    process = subprocess.Popen(
        [_executable(), "server", "run", "--env-file", str(path)],
        stdout=log,
        stderr=subprocess.STDOUT,
        stdin=subprocess.DEVNULL,
        env=env,
        cwd=settings.pc_home,
        start_new_session=True,
    )
    pid_file(settings).write_text(str(process.pid))
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if process.poll() is not None:
            raise ServerError(f"PowerContext Server 启动失败（退出码 {process.returncode}），见 {log_file(settings)}")
        try:
            ready = httpx.get(f"{settings.pc_url}/health/ready", timeout=2.0)
            if ready.status_code == 200 and ready.json().get("status") in {"ready", "degraded"}:
                return dict(status(settings), started=True, readiness=ready.json().get("status"))
        except httpx.HTTPError:
            pass
        time.sleep(0.5)
    raise ServerError(f"PowerContext Server 在 {timeout:.0f}s 内没有就绪，见 {log_file(settings)}")


def stop(settings: Settings, timeout: float = 20.0) -> dict[str, object]:
    pid = read_pid(settings)
    stopped = False
    if pid and _alive(pid):
        try:
            os.killpg(pid, signal.SIGTERM)
        except ProcessLookupError:
            pass
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline and _alive(pid):
            time.sleep(0.3)
        if _alive(pid):
            os.killpg(pid, signal.SIGKILL)
            time.sleep(0.5)
        stopped = True
    pid_file(settings).unlink(missing_ok=True)
    deadline = time.monotonic() + 10
    while time.monotonic() < deadline and _port_open(settings):
        time.sleep(0.3)
    return {"stopped_pid": pid if stopped else None, "live": is_live(settings)}
